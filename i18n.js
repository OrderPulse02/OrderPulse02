let lang = 'en';
try { lang = localStorage.getItem('op_lang') || 'en'; } catch {}
if (!DICT[lang]) lang = 'en';
document.documentElement.lang = lang;

const getLang = () => lang;
function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  document.documentElement.lang = l;
  try { localStorage.setItem('op_lang', l); } catch {}
}
function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return s;
}
function errMsg(e) {
  const code = e?.code;
  if (code && (DICT[lang][code] || DICT.en[code])) return t(code);
  return e?.message && !/^OP_/.test(e.message) ? e.message : t('OP_UNKNOWN');
}
